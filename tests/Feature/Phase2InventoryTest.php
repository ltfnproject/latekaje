    public function test_kkk_toolman_delegation_and_strict_mode_governance(): void
    {
        $kkk = User::updateOrCreate(
            ['email' => 'p2-kkk@latekaje.test'],
            ['name' => 'KKK Fase 2', 'password' => 'secret1234', 'role' => 'admin', 'is_active' => true, 'must_change_password' => false],
        );
        $toolman = User::updateOrCreate(
            ['email' => 'p2-toolman@latekaje.test'],
            ['name' => 'Toolman Fase 2', 'password' => 'secret1234', 'role' => 'staff', 'is_active' => true, 'must_change_password' => false],
        );

        $prevDelegation = Setting::where('key', GovernanceService::KEY_DELEGATION_ENABLED)->value('value');
        $prevUntil = Setting::where('key', GovernanceService::KEY_DELEGATION_UNTIL)->value('value');
        $prevStrict = Setting::where('key', GovernanceService::KEY_PROCUREMENT_STRICT)->value('value');

        try {
            // 1. Default delegasi OFF: Toolman tidak boleh buat Aset maupun Barang Masuk
            GovernanceService::setToolmanDelegation(false, null, $kkk);
            $this->assertFalse(GovernanceService::isToolmanDelegationActive());
            $this->assertTrue(Gate::forUser($kkk)->allows('create', Asset::class));
            $this->assertTrue(Gate::forUser($kkk)->allows('create', Procurement::class));
            $this->assertFalse(Gate::forUser($toolman)->allows('create', Asset::class));
            $this->assertFalse(Gate::forUser($toolman)->allows('create', Procurement::class));

            // 2. Delegasi ON 24 jam: Toolman boleh tambah Aset & Barang Masuk, TAPI tetap tidak boleh lihat harga / hapus
            GovernanceService::setToolmanDelegation(true, 24, $kkk);
            $this->assertTrue(GovernanceService::isToolmanDelegationActive());
            $this->assertNotNull(GovernanceService::toolmanDelegationUntil());
            $this->assertTrue(Gate::forUser($toolman)->allows('create', Asset::class));
            $this->assertTrue(Gate::forUser($toolman)->allows('create', Procurement::class));
            $this->assertFalse($toolman->canViewFinancials());

            // 3. Timer kadaluarsa otomatis mematikan delegasi
            Setting::set(GovernanceService::KEY_DELEGATION_UNTIL, now()->subMinute()->toIso8601String());
            $this->assertFalse(GovernanceService::isToolmanDelegationActive());
            $this->assertFalse(Gate::forUser($toolman)->allows('create', Procurement::class));

            // 4. Mode Ketat Barang Baru toggle
            GovernanceService::setProcurementStrictMode(false, $kkk);
            $this->assertFalse(GovernanceService::isProcurementStrictMode());

            GovernanceService::setProcurementStrictMode(true, $kkk);
            $this->assertTrue(GovernanceService::isProcurementStrictMode());
        } finally {
            Setting::set(GovernanceService::KEY_DELEGATION_ENABLED, (string) ($prevDelegation ?? '0'));
            Setting::set(GovernanceService::KEY_DELEGATION_UNTIL, (string) ($prevUntil ?? ''));
            Setting::set(GovernanceService::KEY_PROCUREMENT_STRICT, (string) ($prevStrict ?? '0'));
            ActivityLog::where('action', 'like', 'governance.%')->where('user_id', $kkk->id)->delete();
            $kkk->delete();
            $toolman->delete();
        }
    }

