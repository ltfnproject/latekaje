            try {
                LoanService::borrow($ramItem->id, 'Siswa Uji', 'XI TJKT 1', '123456');
            } catch (ValidationException) {
                $retireBorrowBlocked = true;
            }
            $this->assertTrue($retireBorrowBlocked, 'unit afkir tidak boleh dipinjam');

            // Pastikan seluruh siklus tercatat di ActivityLog
            $this->assertTrue(ActivityLog::where('action', 'asset_item.installed')->where('subject_id', $pcItem->id)->exists());
            $this->assertTrue(ActivityLog::where('action', 'asset_item.unmounted')->where('subject_id', $ramItem->id)->exists());
            $this->assertTrue(ActivityLog::where('action', 'asset_item.retired')->where('subject_id', $ramItem->id)->exists());
        } finally {
            ActivityLog::where('subject_type', 'AssetItem')->whereIn('subject_id', [$pcItem->id, $ramItem->id])->delete();
            $ramItem->delete();
            $pcItem->delete();
            $ramAsset->delete();
            $pcAsset->delete();
            $kkk->delete();
        }
    }

