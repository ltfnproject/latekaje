            'category_id' => AssetCategory::where('code', 'PC')->value('id'),
            'nama_alat' => 'PC Praktik Uji Pasang',
            'spesifikasi' => 'Core i5 / 8GB',
            'kegunaan' => 'Praktik Siswa',
        ]);
        $ramAsset = Asset::create([
            'category_id' => AssetCategory::where('code', 'CMP')->value('id'),
            'nama_alat' => 'RAM DDR4 8GB Uji Pasang',
            'spesifikasi' => 'Kingston 3200MHz',
            'kegunaan' => 'Praktik Siswa',
        ]);

        $pcItem = AssetItem::create([
            'asset_id' => $pcAsset->id,
            'nomor_seri_atau_qr' => 'P2-PC-9901',
            'kondisi' => 'baik',
            'status' => AssetItem::STATUS_AVAILABLE,
            'location_id' => $gudang->id,
        ]);
        $ramItem = AssetItem::create([
            'asset_id' => $ramAsset->id,
            'nomor_seri_atau_qr' => 'P2-CMP-9901',
            'kondisi' => 'baik',
            'status' => AssetItem::STATUS_AVAILABLE,
            'location_id' => $gudang->id,
        ]);

        try {
            $this->actingAs($kkk);

            // 1. Pasang PC tetap di Lab KKPI
            $pcItem = AssetInstallationService::install($pcItem, $labKkpi->id, null, 'Meja 04', 'PC Praktik Meja 04');
            $this->assertSame(AssetItem::STATUS_INSTALLED, $pcItem->status);
            $this->assertSame($labKkpi->id, $pcItem->location_id);

            // 2. Pasang RAM ke dalam PC-04 (parent-child)
            $ramItem = AssetInstallationService::install($ramItem, null, $pcItem->id, 'Slot DIMM 1', 'Upgrade RAM PC 04');
            $this->assertSame(AssetItem::STATUS_INSTALLED, $ramItem->status);
            $this->assertSame($pcItem->id, $ramItem->parent_asset_item_id);
            $this->assertSame($labKkpi->id, $ramItem->location_id);
            $this->assertSame(1, $pcItem->installedComponents()->count());

            // 3. Unit berstatus 'terpasang' WAJIB terkunci dari peminjaman!
            $borrowBlocked = false;
            try {
                LoanService::borrow($ramItem->id, 'Siswa Uji', 'XI TJKT 1', '123456');
            } catch (ValidationException) {
                $borrowBlocked = true;
            }
            $this->assertTrue($borrowBlocked, 'unit terpasang tidak boleh dipinjam');

            // 4. Copot RAM kembali ke stok Gudang TJKT
            $ramItem = AssetInstallationService::unmountToStock($ramItem, null, 'Almari Komponen', 'Diganti keping baru');
            $this->assertSame(AssetItem::STATUS_AVAILABLE, $ramItem->status);
            $this->assertNull($ramItem->parent_asset_item_id);
            $this->assertSame($gudang->id, $ramItem->location_id);

            // 5. Tandai RAM sebagai Afkir → tidak boleh dipinjam
            $ramItem = AssetInstallationService::retire($ramItem, 'Pin terbakar');
            $this->assertSame(AssetItem::STATUS_RETIRED, $ramItem->status);

